#!/usr/bin/env python3
"""Regenerate src/lm3-recon-data.js - the Light Master 3 spectrum reconstruction.

    uv run --with numpy python scripts/fit-lm3-recon.py path/to/IESTM30_15_Sspds.dat

Inputs
  - The 318 IES TM-30 sample spectra (380..780 nm at 1 nm, one column per source,
    first column wavelength), e.g. luxpy's data/spds/IESTM30_15_Sspds.dat.
  - test/fixtures/as7262-response.json - AS7262 spectral responsivity, from the
    vector curves of Figure 13 in the ams datasheet (v1-01).
  - DAYLIGHT_RAW / DAYLIGHT_K below: a Light Master III reading of window daylight
    (lamp off) on 4 Nov 2026, assumed to be CIE D55 (the LM4 read 5,500 K).
    Calibrating against D50 or D65 instead moves the bench Ra by under 1.5.

Method
  - Prior: the TM-30 spectra (McCamy CCT 1500-10000 K) plus Planckian 2000-7000 K and CIE daylight
    4000-10000 K series, each normalised to Y = 1.
  - Wiener estimator W = R A^T (A R A^T + lam I)^-1, with R the prior's
    autocorrelation and A the 6 x 81 sensor matrix.
  - Gains: the meter's relative band sensitivity, LM3 band / simulated band on
    D55. In the app, spd = max(0, W (channels / gains)).
  - Lux scale: lux = scale x photopic Y(spd), anchored to Opple's matrix lux on
    the 4000 K frame of test/fixtures/bench-2026-11-04.json.

Cross-validated on the library (5-fold), median |Ra error| ~1.5, phosphor LEDs ~1.0.
"""
import json
import struct
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
LAM = 1e-4
DAYLIGHT_RAW = [196.5, 215.5, 278.5, 299, 314, 358]
DAYLIGHT_K = [1.1345, 1.1106, 1.1470, 1.2314, 1.1557, 1.1826]
OPPLE_GENERAL_Y = [-0.19865, 0.01337, 0.40651, 0.29702, -0.06287, 0.03282]  # src/lm3.js MATRICES[2][1]

JS = """
const C = await import(%r);
const D = await import(%r);
const P = [];
for (let t = 2000; t <= 7000; t += 100) P.push(C.spdOfPlanck(t));
for (let t = 4000; t <= 10000; t += 250) P.push(C.spdOfD(t));
console.log(JSON.stringify({ P, D55: C.spdOfD(5500), cmf: Array.from(D.CMF_1931_2DEG) }));
""" % (str(ROOT / 'src/colour.js'), str(ROOT / 'src/cie-data.js'))


def main() -> None:
    rows = [line.strip().rstrip(',').split(',') for line in open(sys.argv[1])]
    wl = np.array([float(r[0]) for r in rows])
    lib = np.array([[float(v) for v in r[1:]] for r in rows])[(wl - 380) % 5 == 0].T  # sources x 81
    js = json.loads(subprocess.run(['node', '--input-type=module', '-e', JS], capture_output=True, text=True, check=True).stdout)
    cmf = np.array(js['cmf']).reshape(81, 3)
    ybar = cmf[:, 1]
    # keep library sources with a McCamy CCT of 1500-10000 K (the range CRI is scored over)
    XYZ = lib @ cmf
    x, y = XYZ[:, 0] / XYZ.sum(1), XYZ[:, 1] / XYZ.sum(1)
    n = (x - 0.332) / (0.1858 - y)
    cct = 449 * n**3 + 3525 * n**2 + 6823.3 * n + 5520.33
    lib = lib[(cct > 1500) & (cct < 10000)]
    prior = np.vstack([lib, np.array(js['P'])])
    prior = prior[(prior @ ybar) > 0]
    prior = prior / (prior @ ybar)[:, None]

    resp = json.load(open(ROOT / 'test/fixtures/as7262-response.json'))['channels']
    A = np.array([resp[c] for c in 'VBGYOR'])
    R = prior.T @ prior / len(prior)
    G = A @ R @ A.T
    W = R @ A.T @ np.linalg.inv(G + LAM * np.trace(G) / 6 * np.eye(6))

    day = np.array(DAYLIGHT_K) * np.array(DAYLIGHT_RAW)
    gains = day / (A @ np.array(js['D55']))
    gains = gains / gains[2]

    # Lux scale: photopic Y of the reconstruction is set equal to Opple's general-mode
    # matrix lux on the 4000 K bench frame - the level Nat checked against lux-1.
    bench = json.load(open(ROOT / 'test/fixtures/bench-2026-11-04.json'))
    cal = bytes.fromhex(bench['calibration']['lm3'])[11:]
    k = [struct.unpack('<f', cal[1 + 4 * i:5 + 4 * i])[0] for i in range(7)]
    meas = bytes.fromhex(next(p['lm3'] for p in bench['points'] if p['label'] == '4000 K'))[11:]
    ch = np.array([((meas[1 + 2 * i] << 8) | meas[2 + 2 * i]) * k[i] for i in range(6)])
    matrix_lux = float(np.dot(OPPLE_GENERAL_Y, ch))
    recon_y = float(ybar @ np.clip(W @ (ch / gains), 0, None))
    lux_scale = matrix_lux / recon_y

    f = lambda v: ('%.6g' % v).replace('e-0', 'e-')
    body = ',\n'.join('  [' + ', '.join(f(v) for v in r) + ']' for r in W)
    out = f"""// Light Master 3 spectrum reconstruction (Wiener estimator), generated by
// scripts/fit-lm3-recon.py - do not edit by hand.
//
// LM3_RECON_W maps the six sensor bands (kSensor-calibrated, then divided by
// LM3_RECON_GAINS) to a spectral power distribution at 380..780 nm in 5 nm
// steps (81 rows x 6 columns). It was fitted on the 318 IES TM-30 sample
// spectra plus Planckian (2000-7000 K) and CIE daylight (4000-10000 K) series,
// using the AS7262 spectral responsivity from the ams datasheet (Figure 13).
// LM3_RECON_GAINS are the meter's relative band sensitivities, measured on a
// real Light Master III under daylight (4 Nov 2026) against CIE D55.
export const LM3_RECON_GAINS = [{', '.join(f(v) for v in gains)}];

// Lux = LM3_LUX_SCALE x photopic Y of the reconstructed spectrum (general-mode
// sources). Set so it equals Opple's matrix lux on the 4000 K bench frame, where
// the LM3 matched a Yocto-Light-V5 lux sensor (4 Nov 2026).
export const LM3_LUX_SCALE = {f(lux_scale)};

export const LM3_RECON_W = [
{body},
];
"""
    (ROOT / 'src/lm3-recon-data.js').write_text(out)
    print('gains', np.round(gains, 4), 'lux scale', f(lux_scale))


if __name__ == '__main__':
    main()
